"""Turn a configure-generated (cross) Makefile into RISCOS/Makefile.

Usage: python3 RISCOS/mkmakefile.py <configured build dir>/Makefile RISCOS/Makefile

See RISCOS/BUILDING for how to produce the configured Makefile.  The
result is the hand maintained RISCOS/Makefile, so any further edits made
to that file need to be added here too (or made again) when regenerating.
"""
import re, sys
src, dst = sys.argv[1], sys.argv[2]
s = open(src).read()

def sub(pattern, repl, count=1, flags=re.M):
    global s
    new, n = re.subn(pattern, repl, s, count=count, flags=flags)
    if n == 0:
        sys.exit(f"no match: {pattern}")
    s = new

header = '''# Makefile for Python on RISC OS
#
# This file is hand maintained.  It was generated by running configure in
# cross-compile mode with the GCCSDK cross compiler (arm-riscos-gnueabihf),
# and then edited for RISC OS by RISCOS/mkmakefile.py.  See RISCOS/BUILDING.
#
# Build from the top of the source tree with:
#
#     make -f RISCOS/Makefile BUILD_PYTHON=/path/to/python3.14
#
# BUILD_PYTHON must be a Python of the same version (3.14) for the host.
# It is used to freeze modules and run the code generators.

# === RISC OS toolchain ===
CROSS_PREFIX ?=	arm-riscos-gnueabihf-
BUILD_PYTHON ?=	python3.14
# libdl lives in the toolchain's top level lib directory
TOOLCHAIN_LIBDIR ?= $(abspath $(dir $(shell command -v $(CROSS_PREFIX)gcc))../lib)
MAKEFILE=	$(srcdir)/RISCOS/Makefile

'''
s = header + s

# --- Paths and toolchain ---------------------------------------------------
sub(r'^srcdir=.*$', 'srcdir=\t\t.')
sub(r'^VPATH=.*$', 'VPATH=\t\t.')
sub(r'^abs_srcdir=.*$', 'abs_srcdir=\t$(CURDIR)')
sub(r'^abs_builddir=.*$', 'abs_builddir=\t$(CURDIR)')
sub(r'^CC=.*$', 'CC=\t\t$(CROSS_PREFIX)gcc')
sub(r'^CXX=.*$', 'CXX=\t\t$(CROSS_PREFIX)g++')
sub(r'^AR=.*$', 'AR=\t\t$(CROSS_PREFIX)ar')
sub(r'^READELF=.*$', 'READELF=\t$(CROSS_PREFIX)readelf')
sub(r'^SOABI=.*$', 'SOABI=\t\tcpython-314-arm-riscos')
sub(r'^EXT_SUFFIX=.*$', 'EXT_SUFFIX=\t.$(SOABI)$(SHLIB_SUFFIX)')
sub(r'^BASECPPFLAGS=.*$', 'BASECPPFLAGS=\t-I$(srcdir)/RISCOS -IObjects -IInclude -IPython')
sub(r'^CONFIGURE_LDFLAGS=.*$', 'CONFIGURE_LDFLAGS=\t$(if $(TOOLCHAIN_LIBDIR),-L$(TOOLCHAIN_LIBDIR))')
sub(r'^MACHDEP=.*$', 'MACHDEP=\triscos')
sub(r'^CONFIG_ARGS=.*$', 'CONFIG_ARGS=')
sub(r'^PYTHON_FOR_REGEN\?=.*$', 'PYTHON_FOR_REGEN?=$(BUILD_PYTHON)')
sub(r'^PYTHON_FOR_FREEZE=.*$', 'PYTHON_FOR_FREEZE=$(BUILD_PYTHON)')
sub(r'^(PYTHON_FOR_BUILD=.*) \S+python3\.14$',
    r'\1 $(BUILD_PYTHON)')
s = s.replace('_PYTHON_SYSCONFIGDATA_PATH=$(shell test -f pybuilddir.txt && echo $(abs_builddir)/`cat pybuilddir.txt`)',
              '_PYTHON_SYSCONFIGDATA_PATH=$(abs_builddir)/$(PYBUILDDIR)')
sub(r'^_PYTHON_HOST_PLATFORM=.*$', '_PYTHON_HOST_PLATFORM=riscos-arm')
sub(r'^HOST_GNU_TYPE=.*$', 'HOST_GNU_TYPE=\tarm-riscos-gnueabihf')
assert '/home/' not in s, [l for l in s.splitlines() if '/home/' in l]

# --- Modules ---------------------------------------------------------------
# posixmodule.c provides the "riscos" module, and swi is built in
sub(r'^(MODBUILT_NAMES=\s+.*)$', r'\1  swi')
s = re.sub(r'^(MODBUILT_NAMES=.*?)\bposix\b', r'\1riscos', s, count=1, flags=re.M)
sub(r'^(MODOBJS=\s+.*)$', r'\1  RISCOS/swimodule.o')
sub(r'^\t\tModules/getpath\.o \\$', '\t\tRISCOS/getpath.o \\\\')

# pyconfig.h is RISCOS/pyconfig.h
sub(r'^\t\tpyconfig\.h \\$', '\t\t$(srcdir)/RISCOS/pyconfig.h \\\\')
s = s.replace('$(INSTALL_DATA) pyconfig.h $(DESTDIR)', '$(INSTALL_DATA) $(srcdir)/RISCOS/pyconfig.h $(DESTDIR)')

# Modules that do not build with UnixLib
def disable_module(name):
    global s
    for var in ('MODBUILT_NAMES', 'MODSHARED_NAMES'):
        s = re.sub(rf'^({var}=.*?)\s+{re.escape(name)}(?=\s|$)', r'\1', s, count=1, flags=re.M)
    s = re.sub(rf'^(SHAREDMODS=.*?)\s*Modules/{re.escape(name)}\$\(EXT_SUFFIX\)', r'\1', s, count=1, flags=re.M)
    sub(rf'^(MODULE_{name.upper()}_STATE=).*$', r'\1disabled')
    sub(r'^(MODDISABLED_NAMES=.*)$', rf'\1 {name}')

disable_module('resource')    # UnixLib's <sys/resource.h> is incomplete

# --- Rules -----------------------------------------------------------------
# Rules that depend on "Makefile" should depend on this file
s = re.sub(r'^([^\t#][^=\n]*:[^=\n]*?)(?<=\s)Makefile(?=\s|$)', r'\1$(MAKEFILE)', s, flags=re.M)

sub(r'^build_all:.*\n(\t.*\n)?', '''build_all:	$(BUILDPYTHON) platform sharedmods
''')

# Modules/config.c is hand maintained in RISCOS/config.c
start = s.index('Makefile Modules/config.c: Makefile.pre')
end = s.index('@echo "The Makefile was updated, you may need to re-run make."', start)
end = s.index('\n', end) + 1
s = s[:start] + '''Modules/config.c: $(srcdir)/RISCOS/config.c
	cp $(srcdir)/RISCOS/config.c $@
''' + s[end:]

# No config.status: Setup.bootstrap and Setup.stdlib are not used
s = re.sub(r'^Modules/Setup\.(bootstrap|stdlib): .*config\.status\n\t\./config\.status \$@\n\n', '', s, flags=re.M)

# getpath: RISCOS/getpath.c replaces Modules/getpath.c
start = s.index('Modules/getpath.o: $(srcdir)/Modules/getpath.c')
end = s.index('-o $@ $(srcdir)/Modules/getpath.c', start)
end = s.index('\n', end) + 1
s = s[:start] + '''RISCOS/getpath.o: $(srcdir)/RISCOS/getpath.c $(MAKEFILE) $(PYTHON_HEADERS)
	$(CC) -c $(PY_CORE_CFLAGS) \\
		-DPYTHONPATH='""' \\
		-DPREFIX='"<Python3$$Dir>"' \\
		-DEXEC_PREFIX='"<Python3$$Dir>"' \\
		-DVPATH='""' \\
		-o $@ $(srcdir)/RISCOS/getpath.c

RISCOS/swimodule.o: $(srcdir)/RISCOS/swimodule.c $(MODULE_DEPS_STATIC) $(PYTHON_HEADERS)
	$(CC) $(PY_BUILTIN_MODULE_CFLAGS) -c $(srcdir)/RISCOS/swimodule.c -o $@
''' + s[end:]

# pybuilddir.txt: the location of the shared modules in the build tree.
# It is read on RISC OS, so contains the RISC OS form of the name.
start = s.index('pybuilddir.txt: $(PYTHON_FOR_BUILD_DEPS)')
end = s.index('\tfi\n', start) + len('\tfi\n')
s = s[:start] + '''PYBUILDDIR=	build/lib.$(_PYTHON_HOST_PLATFORM)-$(VERSION)

pybuilddir.txt: $(MAKEFILE)
	@$(MKDIR_P) $(PYBUILDDIR)
	echo "$(PYBUILDDIR)" | sed 'y|./|/.|' > $@
''' + s[end:]
s = s.replace('''sharedmods: $(SHAREDMODS) pybuilddir.txt
	@target=`cat pybuilddir.txt`; \\''', '''sharedmods: $(SHAREDMODS) pybuilddir.txt
	@target=$(PYBUILDDIR); \\''')
assert 'target=$(PYBUILDDIR)' in s
open(dst, 'w').write(s)
print("written", dst)
