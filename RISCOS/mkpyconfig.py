"""Turn a configure-generated (cross) pyconfig.h into RISCOS/pyconfig.h.

Usage: python3 RISCOS/mkpyconfig.py <configured build dir>/pyconfig.h RISCOS/pyconfig.h

See RISCOS/BUILDING for how to produce the configured pyconfig.h.
"""
import re
import sys

# Functions that UnixLib has, but which the earlier RISC OS ports left
# disabled (or which do not work as Python expects).  Keep them off until
# they have been tested on RISC OS.
OFF = '''
    HAVE_CHROOT HAVE_CTERMID HAVE_EVENTFD HAVE_SYS_EVENTFD_H HAVE_FCHMOD
    HAVE_FCHOWN HAVE_FPATHCONF HAVE_FSEEKO HAVE_FSYNC HAVE_GETGRGID_R
    HAVE_GETGRNAM_R HAVE_GETGROUPLIST HAVE_GETGROUPS HAVE_GETPGRP
    HAVE_GETPWENT HAVE_GETPWNAM_R HAVE_GETPWUID_R HAVE_INITGROUPS HAVE_LINK
    HAVE_LOCKF HAVE_MAKEDEV HAVE_PATHCONF HAVE_PAUSE HAVE_POLL
    HAVE_PTHREAD_CONDATTR_SETCLOCK HAVE_SETEGID HAVE_SETEUID HAVE_SETGID
    HAVE_SETGROUPS HAVE_SETPGID HAVE_SETPGRP SETPGRP_HAVE_ARG HAVE_SETUID
    HAVE_SHM_OPEN HAVE_SHM_UNLINK HAVE_SIGACTION HAVE_SIGALTSTACK
    HAVE_SIGFILLSET HAVE_SYMLINK HAVE_SYNC HAVE_TIMES HAVE_WCSCOLL
    HAVE_WCSFTIME HAVE_WCSXFRM PY_COERCE_C_LOCALE WITH_PYMALLOC
    HAVE_TTYNAME_R
    _FILE_OFFSET_BITS _LARGEFILE_SOURCE HAVE_LARGEFILE_SUPPORT
'''.split()

# Results of run-time checks that cannot be made when cross compiling, and
# things the earlier ports had enabled.
ON = {
    'HAVE_BROKEN_MBSTOWCS': '1',
    'HAVE_COMPUTED_GOTOS': '1',
    'HAVE_WORKING_TZSET': '1',
    'HAVE_DECL_TZNAME': '1',
    'HAVE_DLOPEN': '1',
    'HAVE_DLADDR': '1',
    'HAVE_DYNAMIC_LOADING': '1',
    'HAVE_LIBDL': '1',
    'HAVE_MADVISE': '1',
    'HAVE_MKFIFO': '1',
}

# off_t is 32 bits, as in earlier ports
VALUES = {
    'SIZEOF_OFF_T': '4',
    'SIZEOF_FPOS_T': '4',
}

HEADER = '''#ifndef Py_PYCONFIG_H
#define Py_PYCONFIG_H

/* pyconfig.h for RISC OS (GCCSDK / UnixLib, arm-riscos-gnueabihf).

   This file is hand maintained.  It was generated by running configure in
   cross-compile mode against the UnixLib headers and libraries, then edited
   by RISCOS/mkpyconfig.py:

   - functions that UnixLib has but which the earlier RISC OS ports left
     disabled are left disabled;
   - results of run-time checks that cannot be made when cross compiling
     are filled in;
   - off_t is kept at 32 bits, as in earlier ports.

   RISCOS is used throughout the sources for RISC OS specific code. */

#if defined(__riscos__) && !defined(RISCOS)
#define RISCOS 1
#endif
'''


def main(src, dst):
    s = open(src).read()
    seen = set()

    def sub_define(m):
        name = m.group(1)
        seen.add(name)
        if name in OFF:
            return f'/* #undef {name} */'
        if name in VALUES:
            return f'#define {name} {VALUES[name]}'
        return m.group(0)

    def sub_undef(m):
        name = m.group(1)
        seen.add(name)
        if name in ON:
            return f'#define {name} {ON[name]}'
        return m.group(0)

    s = re.sub(r'^#define (\w+)\b.*$', sub_define, s, flags=re.M)
    s = re.sub(r'^/\* #undef (\w+) \*/$', sub_undef, s, flags=re.M)
    missing = [n for n in [*OFF, *ON, *VALUES] if n not in seen]
    if missing:
        sys.exit(f'not found in {src}: {" ".join(missing)}')

    start = '#ifndef Py_PYCONFIG_H\n#define Py_PYCONFIG_H\n'
    if start not in s:
        sys.exit(f'unexpected start of {src}')
    s = s.replace(start, HEADER, 1)
    open(dst, 'w').write(s)
    print('written', dst)


if __name__ == '__main__':
    main(*sys.argv[1:])
